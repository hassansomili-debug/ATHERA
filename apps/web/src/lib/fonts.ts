import { IBM_Plex_Sans_Arabic, Inter } from "next/font/google";

/**
 * خطّا الهويّة | The brand typefaces — **مُستضافان عندنا، لا عند غيرنا**.
 *
 * ورقةُ الهويّة تسمّي `Inter` للإنجليزية و`IBM Plex Sans Arabic` للعربية.
 * وكان الاسمان مكتوبَين في الورقة بلا ملفٍّ خلفهما: من كان الخطُّ مثبَّتًا
 * على جهازه رآه، ومن لا فلا — فالهويّةُ تُقرأ عند بعض الناس دون بعض، ولا
 * شيء في الشاشة يقول ذلك.
 *
 * **ولا وسمَ إلى خادمٍ ثالث.** سياسةُ المحتوى في `next.config.mjs` تقول
 * `font-src 'self' data:` — فرابطٌ إلى خطوط Google يُحجب في المتصفّح بلا
 * رسالةٍ مفهومة، ويعود الأمر إلى ما كان وأسوأ. و`next/font` ينزّل الملفّ
 * **وقت البناء** ويخدمه من أصلنا، فيوافق السياسة القائمة ولا يُطلب لها
 * استثناء.
 *
 * والخطّان يخرجان متغيّرَي CSS لا صنفَين، فتبقى الورقةُ هي التي تقرّر أيُّ
 * خطٍّ لأيّ اتجاه — موضعٌ واحد تُقرأ منه المقابلة كلُّها.
 */
export const latin = Inter({
  subsets: ["latin"],
  display: "swap",
  variable: "--font-latin",
});

/**
 * وهذا ليس خطًّا متغيّرًا، فتُطلب أوزانُه بأسمائها: العاديّ للنصّ،
 * والمتوسّط والنصف‑غامق للعناوين وأسماء الأفعال.
 */
export const arabic = IBM_Plex_Sans_Arabic({
  subsets: ["arabic", "latin"],
  weight: ["400", "500", "600", "700"],
  display: "swap",
  variable: "--font-arabic",
});

/** ما يُوضع على `<html>` في القشور الثلاث — لا تتفرّق. */
export const FONT_VARIABLES = `${latin.variable} ${arabic.variable}`;
