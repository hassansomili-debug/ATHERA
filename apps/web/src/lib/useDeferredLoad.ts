import { useEffect, useRef } from "react";

/**
 * بوّابةُ الكتابة: تُنفَّذ `write` **إن كان جيلُها ما يزال هو الحاضر**،
 * وتُهمَل صامتةً إن سبقه غيرُه أو فُكّ التركيب.
 *
 * ولا تُهمل الكتابةُ خطأً: إهمالُها هو الصواب. الردُّ الذي تأخّر يتكلّم عن
 * شاشةٍ لم تعد معروضة، وخبرُه — نجاحًا كان أو فشلًا — لا يخصّ ما يراه
 * الباحثُ الآن.
 */
export type Commit = (write: () => void) => void;

/**
 * تحميل البيانات عند التركيب أو تغيّر الاعتماديات.
 *
 * **لماذا الدورة الصغرى؟** ضبط الحالة تزامنيًا داخل جسم `useEffect` يُطلق
 * تصييرًا متتاليًا، ويمنعه `react-hooks/set-state-in-effect` من إضافات
 * React 19. وخمسَ عشرةَ شاشةً كانت تكتب `useEffect(() => { void load(); })`
 * حيث يضبط `load` الحالة — فتُخالف القاعدة كلها بالنمط نفسه.
 *
 * تأجيل الاستدعاء إلى الدورة الصغرى التالية يجعل ضبط الحالة يقع في **دالة
 * رد نداء** لا في جسم التأثير، وهو بالضبط ما توصي به القاعدة.
 *
 * ## لماذا `commit`، ولماذا لم تكفِ رايةُ `active`
 *
 * كانت هنا رايةٌ تُطفأ عند التنظيف، وكُتب في وصفها أنّها تمنع الكتابةَ بعد
 * فكّ التركيب. **ولم تكن تمنعها.** الرايةُ تُقرأ *قبل* استدعاء `load`، فهي
 * تمنع بدايةً متأخّرة ولا تمنع نهايةً متأخّرة؛ وضبطُ الحالة يقع داخل
 * `load` بعد `await`، حيث لا تُقرأ الرايةُ أصلًا. فما إن ينطلق الطلبُ حتى
 * تصير كتابتُه حتميّة.
 *
 * وأثرُ ذلك في الإنتاج — رُصد في قبول الموجة 1.1 — أنّ طلبَين يتسابقان حين
 * يُبدَّل العرضُ قبل استقرار الأوّل، **فيكتب الأخيرُ وصولًا على الأخير
 * طلبًا**. فتُعرض صفوفُ عرضٍ تحت اسم عرضٍ آخر: القائمةُ المنسدلة تقول
 * «المؤرشفة» والصفوفُ صفوفُ «الكلّ».
 *
 * والعقدُ هنا صريح: **لجيلِ الاعتماديات N، إن بدأ N+1 قبل انتهاء N، فلا
 * يجوز لردّ N أن يكتب حالةً بعد أن صار N+1 هو الحاضر.** وكذلك بعد فكّ
 * التركيب. ولأنّ الكتابة تقع داخل `load`، لا يكفي أن يعرف الخطّافُ وحده؛
 * فيُعطى `load` ما يحترمه: `commit`.
 *
 * ## القاعدةُ التي تُراجَع بها كلّ شاشة
 *
 * **كلُّ كتابةِ حالةٍ تقع بعد `await` تمرّ عبر `commit`.** نجاحًا كان أو
 * `catch` أو `finally` — وأخصُّها ما يُنسى: مسارُ الخطأ ومسارُ إطفاء رايةِ
 * التحميل. أمّا ما يُكتب *قبل* أوّل `await` فهو لجيله بالبناء، إذ لم يبدأ
 * جيلٌ بعده.
 *
 * ولا يُلغى الطلبُ بـ`AbortController`: الإلغاء يرفع `AbortError` فيهبط في
 * `catch` كلِّ شاشة ويُعرض للباحث فشلًا لم يقع، و`finally` تعمل بعده على
 * كلّ حال فتبقى الحاجةُ إلى `commit` قائمة، ويمسّ ذلك مسارَ تجديد الرمز في
 * `api.ts`. فالبوّابةُ وحدها تفي بالعقد، ولا تقترب من المصادقة.
 */
export function useDeferredLoad(load: (commit: Commit) => Promise<void>): void {
  // عدّادٌ لا رايةٌ منطقية: الرايةُ تقول «أُلغي» ولا تقول «أُلغي لصالح مَن»،
  // والمطلوب أن يعرف كلُّ جيلٍ أنّه هو الحاضرُ بعينه لا مجرّد أنّه لم يُلغَ.
  const generation = useRef(0);

  useEffect(() => {
    const mine = (generation.current += 1);
    const commit: Commit = (write) => {
      if (generation.current === mine) write();
    };

    void Promise.resolve().then(() => {
      if (generation.current === mine) return load(commit);
    });

    // التنظيف يُقدّم العدّاد، فيَبطل هذا الجيلُ وكلُّ كتابةٍ متأخّرةٍ منه —
    // سواءٌ خلفه جيلٌ جديد (تغيّرُ اعتمادية) أو لم يخلفه أحد (فكُّ تركيب).
    return () => {
      generation.current += 1;
    };
  }, [load]);
}
