import { useEffect } from "react";

/**
 * تحميل البيانات عند التركيب أو تغيّر الاعتماديات.
 *
 * **لماذا الدورة الصغرى؟** ضبط الحالة تزامنيًا داخل جسم `useEffect` يُطلق
 * تصييرًا متتاليًا، ويمنعه `react-hooks/set-state-in-effect` من إضافات
 * React 19. وإحدى عشرة شاشة كانت تكتب `useEffect(() => { void load(); })`
 * حيث يضبط `load` الحالة — فتُخالف القاعدة كلها بالنمط نفسه.
 *
 * تأجيل الاستدعاء إلى الدورة الصغرى التالية يجعل ضبط الحالة يقع في **دالة
 * رد نداء** لا في جسم التأثير، وهو بالضبط ما توصي به القاعدة. والسلوك لا
 * يتغيّر: الطلب يُرسل مرة واحدة، عند التركيب وعند تغيّر الاعتماديات.
 *
 * **والراية تصلح عطبًا كامنًا:** بلاها تُكتب الحالة بعد فك التركيب إن عاد
 * الطلب متأخرًا — تحذير React المعروف، وكان قائمًا قبل هذا التغيير.
 */
export function useDeferredLoad(load: () => Promise<void>): void {
  useEffect(() => {
    let active = true;
    void Promise.resolve().then(() => {
      if (active) return load();
    });
    return () => {
      active = false;
    };
  }, [load]);
}
