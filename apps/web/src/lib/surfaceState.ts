/**
 * حالاتُ أي سطحٍ غير متزامن — **ستٌّ، ولا تُطوى في ثلاث**.
 *
 * كان الخلط بينها هو مصدر أكثر ما كذبت به هذه الواجهة على أصحابها:
 *
 *   `loading`           سُئل ولم يُجَب بعد
 *   `ready`             جاء الجواب وفيه شيء
 *   `empty`             جاء الجواب ولا شيء فيه
 *   `failed`            لم يأتِ جواب — الشبكة أو الخادم
 *   `permission_denied` جاء الجواب: ليس لك
 *   `needs_action`      جاء الجواب: ينقص فعلٌ منك (إذن، رفع، اعتماد)
 *
 * **و`failed` ليست `empty`.** «لا نتائج» عن بحثٍ فشل تجعل الباحث يظنّ
 * موضوعه بكرًا فيبني عليه رسالةً كاملة — والشبكة وحدها كانت معطوبة.
 * **و`empty` ليست دليلَ عدم.** «لا تناقضات» تعني «لم نجد»، لا «لا يوجد».
 * **و`permission_denied` ليست `failed`.** الأولى فعلٌ يملكه غيرُك، والثانية
 * عطبٌ يُعاد معه المحاولة؛ وزرُّ «إعادة المحاولة» على الأولى استهزاء.
 * **و`needs_action` ليست شيئًا من ذلك**: الطريق مفتوح وينتظر خطوةً منك،
 * فيجب أن تُعرض الخطوة نفسها زرًّا لا أن تُشرح نصًّا.
 */
export type SurfaceState =
  | "loading"
  | "ready"
  | "empty"
  | "failed"
  | "permission_denied"
  | "needs_action";

/** ما يُعرض للأخطاء وحدها — ثلاثٌ من الستّ. */
export type FailureState = "failed" | "permission_denied" | "needs_action";

/**
 * نوعُ العطب من رمز الحالة — **ولا يُستبدل نصُّ الخادم**.
 *
 * الخادم يرسل رسالته باللغتين ومعها رمزُها؛ فهي تبقى هي المعروضة. وما
 * يُشتقّ هنا هو **الفعل التالي** وحده: إعادةُ محاولةٍ لعطبٍ عابر، ولا
 * إعادة لبابٍ ليس لك.
 */
export function failureStateOf(status: number): FailureState {
  if (status === 403) return "permission_denied";
  if (status === 401) return "needs_action";
  return "failed";
}

/** هل يُعرض «إعادة المحاولة»؟ — لا يُعرض على ما لا تُصلحه إعادة. */
export function canRetry(state: FailureState): boolean {
  return state === "failed";
}
