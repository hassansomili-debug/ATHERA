"""حالٌ تقول ما وقع: «لا دليلَ مؤهَّل» | The state that stops the lie (MVP-0.1 P0).

**العطبُ الذي وقع في الإنتاج، لا احتياطٌ نظريّ.**

رسالتان رُفعتا، وقُرئتا، واستُخرج منهما ثلاثٌ وعشرون حقلًا معروضةً على
الصفّ. ثمّ عرضت البطاقةُ بجوارها: «لم يبدأ استخراج الفرص بعد».

**وقد بدأ، وانتهى.** التنقيبُ جرى تلقائيًّا عند اكتمال الاستخراج، وحمّل
الحقائقَ، وصنّفها، فلم يجد فيها مؤهَّلًا واحدًا — كلُّها استُبعدت
بـ`no_extraction_confidence`. فخرج بلا فرصة، ثمّ كتب في العمود
`not_started`: لأنّ مفردات 0031 الخمس لا تحوي ما يقول «جريتُ فلم أجد
دليلًا مؤهَّلًا»، فوقع الاختيارُ على أكذبها.

والفرقُ ليس لغويًّا: «لم يبدأ» تُخبر الباحثَ أنّ ثمّة خطوةً قادمة، فينتظر
ما لن يأتي، ولا يبلغه أنّ الخطأ في دليله هو. **فالمفردةُ الناقصة هي
العطب**، وهذا الترحيل يضيفها.

## حالُ التنقيب بعد هذا الترحيل

  `not_started`          لم يُنادَ التنقيبُ على هذه الرسالة قطّ — وهي
                         قيمةُ العمود الافتراضية وحدها، لا نتيجةَ تشغيل.
  `running`              حارسٌ داخل المعاملة.
  `completed`            **قامت فرصةٌ فعلًا.**
  `withheld`             جرى على دليلٍ قائم فلم تتكوّن فرصة.
  `no_eligible_evidence` **جرى، ولم يكن ثمّة دليلٌ مؤهَّل أصلًا.**
  `failed`               تعثّر التنقيبُ عطبًا.

## توسعةٌ محضة — والخادمُ القائم يبقى صحيحًا عليها

المفردةُ الجديدة عشرون محرفًا، والعمودُ `String(16)`. فيُوسَّع أولًا ثمّ
يُبدَّل القيد، وبهذا الترتيب وحده: قيدٌ يذكر قيمةً لا يتّسع لها العمود
قيدٌ لا يُرضى أبدًا.

**ولا صفَّ يُعاد كتابتُه.** الصفوفُ التي تحمل `not_started` اليوم تبقى كما
هي: منها ما لم يُنقَّب حقًّا، ومنها ما نُقِّب فكذب عليه العمود، **ولا
سبيلَ إلى التمييز بينهما من العمود وحده**. وتخمينُ أيّها أيّ إتلافُ سجلّ
بظنّ. فالتصحيحُ يقع عند التنقيبة التالية، حين يُعاد الفحصُ على دليلٍ صار
مؤهَّلًا، فتُكتب الحالُ الصادقة مكانها.

## والتراجعُ صحيحٌ لا مُتلِف

المفردةُ تسقط، والصفوفُ التي تحملها لا تسقط معها: تُخفَّض إلى `withheld`
— **أقلُّ مفردات 0031 كذبًا عليها**. فهي تقول «جرى ولم تتكوّن فرصة»، وذاك
صادقٌ عليها؛ ولا تقول «اكتمل» (وما اكتمل شيء) ولا «لم يبدأ» (وقد بدأ).
وبها يبقى العمودُ صحيحًا على خادمٍ لا يعرف المفردةَ الجديدة.

ثمّ يُضيَّق العمودُ إلى `String(16)` **بعد** التخفيض، فلا قيمةَ تُقتطع.
"""
